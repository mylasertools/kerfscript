// Writes lib/kerf/symbols.kerf from the MyLaserTools symbol catalogue:
//   node scripts/symbols.mjs path/to/symbols.json
// Only symbols under open licences (Apache-2.0, MIT, CC0-1.0) are taken;
// THIRD-PARTY-NOTICES.md credits their sources.

import { readFileSync, writeFileSync } from 'node:fs';
import { render } from '../dist/index.js';

// The box a path really covers: some symbols draw outside their viewBox,
// or have none
function drawn(d) {
  const r = render(
    `p = [for (s = path_points(${JSON.stringify(d)})) each s];` +
      'echo([min([for (q = p) q[0]]), min([for (q = p) q[1]]), max([for (q = p) q[0]]), max([for (q = p) q[1]])]);',
  );
  const [x0, y0, x1, y1] = JSON.parse(r.echoes[0]);
  const r3 = (v) => Math.round(v * 1000) / 1000;
  return [r3(x0), r3(y0), r3(x1 - x0), r3(y1 - y0)];
}

const catalogue = JSON.parse(readFileSync(process.argv[2], 'utf8'));
const OPEN = new Set(['Apache-2.0', 'MIT', 'CC0-1.0']);
const kept = catalogue.filter((s) => OPEN.has(s.license)).sort((a, b) => (a.id < b.id ? -1 : 1));
const sources = [...new Set(kept.map((s) => `${s.source}|${s.license}`))].sort();
const q = (s) => JSON.stringify(s);
const rows = kept.map((s) => {
  const path = s.path.replace(/\s+/g, ' ').trim();
  const vb = drawn(path);
  // The icon's own grid: its viewBox, 24 x 24 for Material Design Icons,
  // otherwise what it draws
  const grid = s.viewBox
    ? s.viewBox
        .trim()
        .split(/[\s,]+/)
        .map(Number)
    : /Material Design Icons/.test(s.source)
      ? [0, 0, 24, 24]
      : vb;
  return `  [${q(s.id)}, ${q(s.category)}, [${vb.join(', ')}], ${sources.indexOf(`${s.source}|${s.license}`)}, ${q(path)}, [${grid.join(', ')}]]`;
});
const out = `// kerf/symbols: ${kept.length} pictograms by name, for engraving and cutting.
// The library code: Copyright (c) 2026 MyLaserTools. AGPL-3.0-only or
// MyLaserTools commercial licence. The symbols come from open icon sets,
// each under its own licence (Apache-2.0, MIT or CC0-1.0): symbol_source()
// names it, and THIRD-PARTY-NOTICES.md has the notices.
// Generated by scripts/symbols.mjs. Do not edit.

// A symbol \`size\` mm across the longer side of what it draws, centred on
// the origin (or with its bottom left corner there, center = false). The names are as
// symbol_names() lists them: "heart", "star", "paw", "tree" and the like.
// box = "grid" sizes and places it by its icon set's grid (24 x 24 for
// Material Design Icons) instead, so icons of one set line up as drawn.
// solid = true cuts it as one silhouette, gaps narrower than 2 * close
// closed and its holes filled, with the drawing's detail engraved on it:
// a pictogram drawn as separate strokes (a moon and stars, yarn) cut out
// in one piece. bridge = w also joins pieces too far apart to close, by
// strips w wide.
module symbol(name, size = 10, center = true, fill = "nonzero", box = "drawn", solid = false, close = undef, bridge = undef) {
  assert(box == "drawn" || box == "grid", "box is \\"drawn\\" or \\"grid\\"");
  s = symbol_entry(name);
  vb = box == "grid" ? s[5] : s[2];
  k = size / max(vb[2], vb[3]);
  module drawn() translate(center ? [0, 0] : [vb[2] * k / 2, vb[3] * k / 2])
    scale([k, -k]) translate([-vb[0] - vb[2] / 2, -vb[1] - vb[3] / 2])
      path(s[4], fill = fill, close = true);
  r = is_undef(close) ? size / 30 : close;
  module silhouette() if (is_undef(bridge)) fill_holes() close(r) drawn();
  else join_islands(bridge) fill_holes() close(r) drawn();
  if (solid) {
    silhouette();
    engrave() difference() {
      silhouette();
      drawn();
    }
  } else drawn();
}

// [width, height] of what a symbol draws when it is \`size\` across its
// longer side (box = "drawn"), or across its grid's (box = "grid")
function symbol_size(name, size = 10, box = "drawn") = let (
  s = symbol_entry(name), vb = s[2], g = box == "grid" ? s[5] : vb, k = size / max(g[2], g[3])
) [vb[2] * k, vb[3] * k];

// The names of all symbols, or of one category: ${[...new Set(kept.map((s) => s.category))].sort().join(', ')}
function symbol_names(category = undef) = [for (s = SYMBOLS) if (is_undef(category) || s[1] == category) s[0]];

// Where a symbol comes from and its licence, as [source, licence]
function symbol_source(name) = let (s = symbol_entry(name)) split(SYMBOL_SOURCES[s[3]], "|");

// A symbol's row of SYMBOLS: [name, category, [x, y, w, h] drawn, source,
// path, [x, y, w, h] of its icon grid]
function symbol_entry(name) = let (hit = [for (s = SYMBOLS) if (s[0] == name) s])
  len(hit) ? hit[0] : assert(false, str("No symbol named \\"", name, "\\". symbol_names() lists them."));

SYMBOL_SOURCES = [
${sources.map((s) => `  ${q(s)}`).join(',\n')}
];

SYMBOLS = [
${rows.join(',\n')}
];
`;
writeFileSync('lib/kerf/symbols.kerf', out);
console.log(`${kept.length} symbols from ${sources.length} sources`);
